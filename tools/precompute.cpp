// Generates the preflop odds table for all 169 starting hands against 1..9
// random opponents, as a C++ include (src/preflop_table.inc) and a CSV.
//
// usage: precompute [--out FILE.inc] [--csv FILE.csv]
//                   [--trials-hu N] [--trials-multi N] [--threads N]

#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

#include "holdem/preflop.hpp"
#include "holdem/simulator.hpp"

using namespace holdem;

int main(int argc, char** argv) {
  std::string out_path = "src/preflop_table.inc";
  std::string csv_path = "data/preflop_odds.csv";
  std::uint64_t trials_hu = 2'000'000;
  std::uint64_t trials_multi = 200'000;
  unsigned threads = 0;

  for (int i = 1; i < argc; ++i) {
    auto next = [&](const char* flag) -> const char* {
      if (i + 1 >= argc) { std::cerr << flag << " needs a value\n"; std::exit(2); }
      return argv[++i];
    };
    if (!std::strcmp(argv[i], "--out")) out_path = next("--out");
    else if (!std::strcmp(argv[i], "--csv")) csv_path = next("--csv");
    else if (!std::strcmp(argv[i], "--trials-hu")) trials_hu = std::strtoull(next("--trials-hu"), nullptr, 10);
    else if (!std::strcmp(argv[i], "--trials-multi")) trials_multi = std::strtoull(next("--trials-multi"), nullptr, 10);
    else if (!std::strcmp(argv[i], "--threads")) threads = static_cast<unsigned>(std::strtoul(next("--threads"), nullptr, 10));
    else { std::cerr << "unknown argument: " << argv[i] << "\n"; return 2; }
  }

  std::vector<std::vector<PreflopOdds>> table(kMaxTableOpponents,
                                              std::vector<PreflopOdds>(kNumStartingHands));
  std::uint64_t trials_for[kMaxTableOpponents];
  const auto start = std::chrono::steady_clock::now();

  for (int opp = 1; opp <= kMaxTableOpponents; ++opp) {
    const std::uint64_t trials = opp == 1 ? trials_hu : trials_multi;
    trials_for[opp - 1] = trials;
    for (int idx = 0; idx < kNumStartingHands; ++idx) {
      SimConfig cfg;
      cfg.hero = representative_hand(idx);
      cfg.opponents = opp;
      cfg.trials = trials;
      cfg.threads = threads;
      cfg.seed = 0xC0FFEEULL * 1000 + static_cast<std::uint64_t>(opp) * 1000 + idx;
      const SimResult r = simulate(cfg);
      table[opp - 1][idx] = {static_cast<float>(r.win_rate()), static_cast<float>(r.tie_rate()),
                             static_cast<float>(r.equity())};
    }
    const double elapsed =
        std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
    std::fprintf(stderr, "  %d opponent(s) done  (%.1fs elapsed)\n", opp, elapsed);
  }

  std::ofstream inc(out_path);
  if (!inc) { std::cerr << "cannot write " << out_path << "\n"; return 1; }
  inc << "// GENERATED by tools/precompute.cpp — do not edit by hand.\n"
      << "// Monte Carlo trials per hand: " << trials_hu << " heads-up, " << trials_multi
      << " for 2-9 opponents.\n"
      << "// Layout: kPreflopTable[opponents - 1][starting_hand_index] = {win, tie, equity}\n\n";
  inc << "constexpr std::uint64_t kTableTrials[" << kMaxTableOpponents << "] = {";
  for (int o = 0; o < kMaxTableOpponents; ++o) inc << (o ? ", " : "") << trials_for[o];
  inc << "};\n\n";
  inc << "constexpr PreflopOdds kPreflopTable[" << kMaxTableOpponents << "][" << kNumStartingHands
      << "] = {\n";
  char buf[128];
  for (int o = 0; o < kMaxTableOpponents; ++o) {
    inc << "  { // " << (o + 1) << " opponent(s)\n";
    for (int i = 0; i < kNumStartingHands; ++i) {
      const auto& p = table[o][i];
      std::snprintf(buf, sizeof buf, "    {%.6ff, %.6ff, %.6ff},  // %s\n", p.win, p.tie, p.equity,
                    starting_hand_name(i).c_str());
      inc << buf;
    }
    inc << "  },\n";
  }
  inc << "};\n";

  std::ofstream csv(csv_path);
  if (csv) {
    csv << "hand,index,combos";
    for (int o = 1; o <= kMaxTableOpponents; ++o) csv << ",equity_vs_" << o;
    csv << ",win_vs_1,tie_vs_1\n";
    for (int i = 0; i < kNumStartingHands; ++i) {
      csv << starting_hand_name(i) << ',' << i << ',' << combos_in_class(i);
      for (int o = 0; o < kMaxTableOpponents; ++o) {
        std::snprintf(buf, sizeof buf, ",%.4f", table[o][i].equity);
        csv << buf;
      }
      std::snprintf(buf, sizeof buf, ",%.4f,%.4f\n", table[0][i].win, table[0][i].tie);
      csv << buf;
    }
  } else {
    std::cerr << "warning: cannot write " << csv_path << "\n";
  }

  std::cerr << "wrote " << out_path << " and " << csv_path << "\n";
  return 0;
}
